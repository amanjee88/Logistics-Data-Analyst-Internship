def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = tcPr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tcPr.append(shd)
    shd.set(qn("w:fill"), fill)

def set_cell_margins(cell, top=90, start=100, bottom=90, end=100):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = tcPr.first_child_found_in("w:tcMar")
    if tcMar is None:
        tcMar = OxmlElement('w:tcMar')
        tcPr.append(tcMar)
    for m, v in [('top', top), ('start', start), ('bottom', bottom), ('end', end)]:
        node = tcMar.find(qn('w:' + m))
        if node is None:
            node = OxmlElement('w:' + m); tcMar.append(node)
        node.set(qn('w:w'), str(v)); node.set(qn('w:type'), 'dxa')

def set_repeat_table_header(row):
    trPr = row._tr.get_or_add_trPr()
    tblHeader = OxmlElement('w:tblHeader')
    tblHeader.set(qn('w:val'), 'true')
    trPr.append(tblHeader)

def set_cell_text(cell, text, bold=False, color=DARK, size=9.0):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.line_spacing = 1.06
    r = p.add_run(str(text))
    r.bold = bold; r.font.name = "Arial"; r.font.size = Pt(size); r.font.color.rgb = RGBColor.from_string(color)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    set_cell_margins(cell)

def style_table(table, header=True, font_size=8.8, widths=None):
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    for ridx, row in enumerate(table.rows):
        if header and ridx == 0:
            set_repeat_table_header(row)
        for cidx, cell in enumerate(row.cells):
            set_cell_margins(cell)
            if header and ridx == 0:
                shade(cell, NAVY)
                for p in cell.paragraphs:
                    for r in p.runs:
                        r.bold = True; r.font.color.rgb = RGBColor(255,255,255); r.font.size = Pt(font_size); r.font.name = "Arial"
            else:
                if ridx % 2 == 0: shade(cell, LIGHT)
                for p in cell.paragraphs:
                    p.paragraph_format.space_after = Pt(0)
                    p.paragraph_format.line_spacing = 1.05
                    for r in p.runs:
                        r.font.name = "Arial"; r.font.size = Pt(font_size); r.font.color.rgb = RGBColor.from_string(DARK)
            if widths and cidx < len(widths):
                cell.width = Inches(widths[cidx])

def add_table(doc, headers, rows, widths=None, font_size=8.8):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    for i, h in enumerate(headers): set_cell_text(t.rows[0].cells[i], h, bold=True, color="FFFFFF", size=font_size)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row): set_cell_text(cells[i], val, size=font_size)
    style_table(t, header=True, font_size=font_size, widths=widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)
    return t

def add_bullet(doc, text, level=0):
    p = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
